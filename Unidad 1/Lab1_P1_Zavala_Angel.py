from typing import Self
class air_fryer:
  def __init__(self, color, brand, size):
    self.color = color
    self.brand = brand
    self.size = size

  def dehydrate(self):
    print("The food is dehydrating...")

  def fry(self):
    print("The food is frying...")

  def defrost(self):
    print("The food is defrosting...")

  def describe(self):
    print(f"This Air Fryer is by {self.brand}",
          f"the color is {self.color}",
          f"and the size is {self.size}")

