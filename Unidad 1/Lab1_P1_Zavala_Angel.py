"""# Lab 1: Bank Account Class
Create a Python program that models a bank account using Object-Oriented Programming.
"""

class bank_account:
  def __init__(self, holder_name, balance):
    self.holder_name = holder_name
    self.balance = float(balance)

  def deposit(self):
    proceed = True
    while proceed:
      amount = float(input("Amount to deposit: $"))
      if amount <= 0:
        print("The amount has to be more than 0...")
      elif amount > 0:
        self.balance += amount
        print(f"Successfully deposited ${amount:.2f}",
              f"New Balance: ${self.balance:.2f}")
        proceed = False
      else:
        print("Invalid input. Please enter a numeric value...")

  def withdraw(self):
    proceed = True
    while proceed:
      amount = float(input("Amount to withdraw: $"))
      if amount <= 0:
        print("The amount has to be more than 0...")
      elif amount > self.balance:
        print("The amount assigned exceed with the current balance...")
      elif amount <= self.balance:
        self.balance -= amount
        print(f"Successfully withdrawn ${amount:.2f}",
              f"New Balance: ${self.balance:.2f}")
        proceed = False
      else:
        print("Inavlid input. Please enter a numeric value")

  def check_balance(self):
    print(f"Current Balance: ${self.balance:.2f}")

bank_account1 = bank_account("Raúl Pérez", 5000)
